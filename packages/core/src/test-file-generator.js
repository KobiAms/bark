/**
 * Utility for generating test files to demonstrate file delivery
 */
import { writeFileSync, mkdtempSync } from 'fs';
import { join } from 'path';
import { tmpdir } from 'os';

export function generateTestImage() {
    const width = 200;
    const height = 200;
    const filename = `test-${Date.now()}.png`;
    const filepath = join(mkdtempSync(join(tmpdir(), 'bark-test-')), filename);

    // Create a simple PNG (1x1 transparent PNG as base64)
    // For testing, we'll create a minimal valid PNG
    const pngHeader = Buffer.from([
        0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, // PNG signature
        0x00, 0x00, 0x00, 0x0D, // IHDR chunk size
        0x49, 0x48, 0x44, 0x52, // IHDR
        0x00, 0x00, 0x00, 0x01, // width: 1
        0x00, 0x00, 0x00, 0x01, // height: 1
        0x08, 0x02, 0x00, 0x00, 0x00, // bit depth, color type, etc.
        0x90, 0x77, 0x53, 0xDE, // CRC
        0x00, 0x00, 0x00, 0x0C, // IDAT chunk size
        0x49, 0x44, 0x41, 0x54, // IDAT
        0x08, 0x99, 0x01, 0x01, 0x00, 0x00, 0xFE, 0xFF, 0x00, 0x00, 0x00, 0x02, // data
        0x00, 0x01, // more data
        0x49, 0xB4, 0xE8, 0xB7, // CRC
        0x00, 0x00, 0x00, 0x00, // IEND chunk size
        0x49, 0x45, 0x4E, 0x44, // IEND
        0xAE, 0x42, 0x60, 0x82  // CRC
    ]);

    writeFileSync(filepath, pngHeader);

    return {
        filePath: filepath,
        mimeType: 'image/png',
        fileName: filename,
        caption: '🎨 Test image from Bark agent!'
    };
}

export function generateTestPdf() {
    const filename = `test-${Date.now()}.txt`;
    const filepath = join(mkdtempSync(join(tmpdir(), 'bark-test-')), filename);

    const content = `
Test File Generated by Bark
============================

This is a test file demonstrating the file delivery feature!

Generated at: ${new Date().toISOString()}
Session: Test

Features:
- Agents can now send files to users
- Supports WhatsApp, Telegram, and other adapters
- Files are streamed directly from disk
- No data copying needed

This proves the FILE_READY event pipeline is working correctly!
    `.trim();

    writeFileSync(filepath, content, 'utf8');

    return {
        filePath: filepath,
        mimeType: 'text/plain',
        fileName: filename,
        caption: '📄 Test document from Bark!'
    };
}

